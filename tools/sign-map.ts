/** Розбір значення traffic_sign (напр. "UA:2.1", "UA:3.29[40]", "UA:5.38;UA:1.31") → перший відомий код. */
export function lookupSign(value: string): { code: string; label: string } | null {
  for (const part of value.split(';')) {
    const m = part.trim().match(/^UA:(\d+(?:\.\d+){0,2})/i);
    if (!m) continue;
    const hit = SIGN_MAP[m[1]] ?? (m[1] === '5.38' ? SIGN_MAP['5.38.1'] : undefined);
    if (hit) return hit;
  }
  return null;
}
